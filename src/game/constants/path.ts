//
// 📐 พื้นฐาน Canvas (ดูเพิ่มจาก src/game/constants/canvas.ts)
//   - CANVAS_WIDTH  = 800  (กว้าง, แกน x)
//   - CANVAS_HEIGHT = 600  (สูง, แกน y)
//   - ⚠️ สำคัญ: แกน y คว่ำ!  y ยิ่งมาก = ยิ่งลงล่าง (ไม่ใช่ขึ้นบน)
//     ดังนั้น (0,0) คือมุมบน-ซ้าย, (800,600) คือมุมล่าง-ขวา
// ---------------------------------------------------------------------------
import { Point } from "../../types/game.types";

// ---------------------------------------------------------------------------
// GAME_PATH: เส้นทางที่ยุงวิ่ง (array ของจุดพิกัด)
//
// 🦟 ยุงจะวิ่งตามจุดเหล่านี้แบบ "ต่อเนื่องกันเป็นเส้นทางเดียว"
//    จากจุดแรก (SPAWN_POSITION) → ไประหว่างจุด → ถึงจุดสุดท้าย (HOME_POSITION)
//
// ✏️ วิธีแก้ไข / อยากปรับ path:
//    1. เพิ่ม ลด หรือย้ายจุดพิกัด (x, y) ใน array นี้ได้อิสระ
//    2. ยุงทุกตัวจะปรับตามอัตโนมัติ (โค้ดฝั่ง Mosquito.update อ่านจาก array นี้)
//    3. ข้อควรระวัง: ทุกจุดต้องอยู่ภายในขอบผัง 0-800 (x) × 0-600 (y)
//       และควรวางให้เส้นไม่ตัดกัน (ดูสวยงาม ไม่ทำให้ยุงข้ามเขต)
//
// 📍 ผังเส้นทางปัจจุบัน (มี 8 จุด, เดินเป็นรูปตัว S คดเคี้ยว):
//   (0,150) → (250,150) → (250,350) → (500,350) → (500,180)
//   → (700,180) → (700,480) → (800,480)
//
// ═══════════════════════════════════════════════════════════════════════════
// 🧠 อธิบายแบบละเอียด: x,y ที่วาดลงไปทำงานอย่างไร ? ยุงเดินตามได้ยังไง ?
// ═══════════════════════════════════════════════════════════════════════════
//
// [1] แกนพิกัดของ Canvas (800 กว้าง × 600 สูง):
//
//       x → (แกนขวา)              x=800 (ขอบขวา)
//     ┌──────────────────────────────┐
//   y │ (0,0)                        │
//   ↓ │ จุดเริ่มมุมบน-ซ้าย            │
//   (แกนลง)│                            │
//     │                            │
//     │                            │
//     │                            │
//   y=600│                            │
//     └──────────────────────────────┘
//      (0,600) มุมล่าง-ซ้าย   (800,600) มุมล่าง-ขวา
//
//   ⚠️ จุดสำคัญที่สุด: แกน y คว่ำ!! (ต่างจากคณิตศาสตร์)
//   - x ยิ่งมาก = เลื่อนไปทางขวา
//   - y ยิ่งมาก = เลื่อนลงล่าง (ไม่ใช่ขึ้นบน!)
//   เช่น จุด (500, 180) อยู่ "สูงกว่า" (500, 480)
//
//
// [2] วาดเส้นทางจริง (path) ของเกม ลงบนผัง 800×600:
//
//   ตัวเลขในช่อง = index ของจุดใน GAME_PATH
//   ● = จุดพิกัด, ═══/║ = เส้นที่ยุงวิ่ง
//
//   x=0     x=250          x=500        x=700        x=800
//     │        │              │             │             │
//     ▼        ▼              ▼             ▼             ▼
//     ┌────────┬──────────────┬─────────────┬─────────────┐
//     │        │              │             │             │
// y=150 ●0═════►1             │             │             │   (0,150)→(250,150)
//     │        │              │             │             │
//     │        │              ├─────────────►             │
// y=180 │        │              │4═══5  (500,180)►(700,180)│
//     │        │              │                          │
// y=350 │        │2════════════►3                        │
//     │        │              │                          │
// y=480 │        │              │                   6══════►7
//     └────────┴──────────────┴──────────────────────────┘
//       ↑จุดเกิด          จุดที่ 4,5 อยู่ชั้นบน         ↑6,7 อยู่ชั้นล่าง
//
//   จะเห็นว่า path นี้เป็น "เส้นคดเคี้ยวรูปคล้าย S" เริ่มซ้ายบน
//   ไล่เลี้ยว ไปขวา → ลงล่าง → ไปขวา → ขึ้นบน → ไปขวา → ลงล่าง → สุดขวา
//
// [3] ยุงวิ่งตาม path ยังไง ? (อธิบายด้วยตัวแปร pathIndex)
//
//   ยุงแต่ละตัวมี `pathIndex` (เริ่ม = 0) ชี้ว่ากำลังเดินไปจุดไหน
//   ทุก frame ยุงจะดู เป้าหมาย = path[pathIndex + 1] แล้วค่อยๆ เคลื่อนเข้าหาจุด
//   นั้นเรื่อยๆ จนถึง แล้วเลื่อน index ไปอีก (ดูโค้ดใน Mosquito.ts → update)
//
//     เวลา        pathIndex  เป้าหมาย          ทิศ          ตำแหน่งยุง
//     ─────────────────────────────────────────────────────────────
//     t=0 เริ่ม        0      จุด1 (250,150)   ➡️ ไปขวา     (0,150)
//     ...เดินขวา...    0      จุด1             ➡️ ไปขวา     (100,150)
//     t=ถึงจุด1        1      จุด2 (250,350)   ⬇️ ลงล่าง   (250,150)
//     ...เดินลง...      1      จุด2             ⬇️ ลงล่าง   (250,250)
//     t=ถึงจุด2        2      จุด3 (500,350)   ➡️ ไปขวา   (250,350)
//     ...ไล่ไปเรื่อยๆ จน index ถึงจุดสุดท้าย...
//     t=ถึงจุด7        7      path[8] ไม่มี     🏠 เข้าบ้านแล้ว
//                             → return false  → ระบบหักเลือด player
//
//   💡 สรุป: ยุงเดินทีละ segment (เส้นตรงระหว่างจุดต่อกัน) ไล่จากจุดแรก
//      ไปจุดสุดท้าย ยิ่งมีจุดเยอะ/ทางเลี้ยวมาก = path ยาวขึ้น = ยุงอยู่
//      บนแผนที่นานขึ้น (ยิงได้ง่ายขึ้น = เกมง่ายขึ้นนิดหน่อย)
//
//   ⚠️ ข้อควรระวังเมื่อแก้พิกัด:
//     1. ทุกจุดต้องอยู่ใน 0-800 (x) และ 0-600 (y)
//     2. อย่าให้เส้นตัด/พาดทับตัวเอง (จะไม่สวย และยุงข้ามเขต)
//     3. จุดแรก = จุดเกิด, จุดสุดท้าย = บ้าน ถ้าเลื่อนลากทั้ง 2 ด้วย
// ---------------------------------------------------------------------------
export const GAME_PATH: Point[] = [
  { x: 0, y: 150 }, // จุด 0 = จุดเกิด (SPAWN_POSITION) — ซ้ายบน
  { x: 250, y: 150 }, // จุด 1 — เลื่อนไปทางขวา (ขนานด้านบน)
  { x: 250, y: 350 }, // จุด 2 — เลื่อนลงล่าง
  { x: 500, y: 350 }, // จุด 3 — เลื่อนไปทางขวา
  { x: 500, y: 180 }, // จุด 4 — เลื่อนขึ้นบน
  { x: 700, y: 180 }, // จุด 5 — เลื่อนไปทางขวา
  { x: 700, y: 480 }, // จุด 6 — เลื่อนลงล่าง
  { x: 800, y: 480 }, // จุด 7 = บ้าน (HOME_POSITION) — ขวาล่าง
];

// ---------------------------------------------------------------------------
// HOME_POSITION: ตำแหน่ง "บ้าน" ของยุง
//   = จุดสุดท้ายของ GAME_PATH
//   เมื่อยุงเดินมาถึงจุดนี้ได้ = ยุงเข้าบ้านแล้ว (จะทำให้ player เสียเลือด/คะแนน)
//   ดึงอัตโนมัติจาก array → ถ้าเพิ่ม/ลดจุดสุดท้ายก็เปลี่ยนตามเอง
// ---------------------------------------------------------------------------
export const HOME_POSITION = GAME_PATH[GAME_PATH.length - 1];

// ---------------------------------------------------------------------------
// SPAWN_POSITION: ตำแหน่ง "เกิด" ของยุง
//   = จุดแรกของ GAME_PATH
//   ยุงตัวใหม่จะโผล่ที่จุดนี้ก่อนเริ่มวิ่งเข้าหาบ้าน
// ---------------------------------------------------------------------------
export const SPAWN_POSITION = GAME_PATH[0];
